const storageKey = "attnwall.locale";
const supportedLocales = new Set(["zh-CN", "en"]);
const readStoredLocale = () => {
  try {
    const value = localStorage.getItem(storageKey);
    if (supportedLocales.has(value)) return value;
  } catch {}
  return null;
};
const detectLocale = () => (navigator.language || "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
let locale = readStoredLocale() || detectLocale();
let userChanged = false;
const textState = new WeakMap();
const attributeState = new WeakMap();
const valueState = new WeakMap();

function translate(source) {
  if (!source) return source;
  const leading = source.match(/^\s*/u)?.[0] || "";
  const trailing = source.match(/\s*$/u)?.[0] || "";
  const core = source.slice(leading.length, source.length - trailing.length);
  if (!core) return source;
  const useEnglish = locale === "en";
  let result = (useEnglish ? english : chinese)[core];
  if (result === undefined) {
    for (const [pattern, replace] of (useEnglish ? dynamicRules : reverseDynamicRules)) {
      const match = core.match(pattern);
      if (match) {
        result = replace(match);
        break;
      }
    }
  }
  if (result === undefined) result = core;
  result = useEnglish
    ? result.replace(/消息已读，已取消补发/g, "Message marked as read; retry cancelled.").replace(/推送服务已接受/g, "Push service accepted").replace(/发送失败/g, "Send failed").replace(/推送失败：/g, "Push failed: ").replace(/未测试/g, "Not tested").replace(/网络错误/g, "Network error").replace(/网络问题/g, "Network issue").replace(/· 将自动重试/g, "· will retry automatically").replace(/· 已安排自动重试/g, "· automatic retry scheduled")
    : result.replace(/Message marked as read; retry cancelled\./g, "消息已读，已取消补发").replace(/Push service accepted/g, "推送服务已接受").replace(/Send failed/g, "发送失败").replace(/Push failed: ?/g, "推送失败：").replace(/Not tested/g, "未测试").replace(/Network error/g, "网络错误").replace(/Network issue/g, "网络问题").replace(/· will retry automatically/g, "· 将自动重试").replace(/· automatic retry scheduled/g, "· 已安排自动重试");
  return result === core ? source : leading + result + trailing;
}

function localizeTextNode(node) {
  const element = node.parentElement;
  if (!element || element.closest("script,style,textarea,code,[data-i18n-skip]") || element.isContentEditable) return;
  const previous = textState.get(node);
  const source = previous && node.data === previous.rendered ? previous.source : node.data;
  const rendered = translate(source);
  textState.set(node, {source, rendered});
  if (node.data !== rendered) node.data = rendered;
}

function localizeAttribute(element, name) {
  const current = element.getAttribute(name);
  if (current === null) return;
  let states = attributeState.get(element);
  if (!states) {
    states = new Map();
    attributeState.set(element, states);
  }
  const previous = states.get(name);
  const source = previous && current === previous.rendered ? previous.source : current;
  const rendered = translate(source);
  states.set(name, {source, rendered});
  if (current !== rendered) element.setAttribute(name, rendered);
}

function localizeValue(element) {
  const source = element.getAttribute("data-i18n-value");
  if (source === null) return;
  const previous = valueState.get(element);
  const current = element.value;
  if (previous && current !== previous.rendered) return;
  const rendered = translate(source);
  valueState.set(element, {rendered});
  if (current !== rendered) element.value = rendered;
}

function visit(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    localizeTextNode(node);
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node;
  if (element.hasAttribute("data-i18n-skip")) return;
  for (const name of ["title", "aria-label", "placeholder", "content"]) localizeAttribute(element, name);
  localizeValue(element);
  if (element.matches("script,style,textarea") || element.isContentEditable) return;
  for (const child of element.childNodes) visit(child);
}

function applyLocale() {
  document.documentElement.lang = locale;
  for (const select of document.querySelectorAll("[data-language-select]")) select.value = locale;
  const root = document.body || document.documentElement;
  if (root) visit(root);
}

function setLocale(next, {userInitiated = false} = {}) {
  if (!supportedLocales.has(next)) return false;
  locale = next;
  if (userInitiated) userChanged = true;
  try { localStorage.setItem(storageKey, locale); } catch {}
  applyLocale();
  window.dispatchEvent(new CustomEvent("attnwall:localechange", {detail: {locale, userInitiated}}));
  return true;
}

document.addEventListener("change", event => {
  if (event.target.matches("[data-language-select]")) setLocale(event.target.value, {userInitiated: true});
});

const observer = new MutationObserver(records => {
  for (const record of records) {
    if (record.type === "characterData") visit(record.target);
    else if (record.type === "attributes") visit(record.target);
    else for (const node of record.addedNodes) visit(node);
  }
});

applyLocale();
if (document.body) observer.observe(document.body, {
  subtree: true,
  childList: true,
  characterData: true,
  attributes: true,
  attributeFilter: ["title", "aria-label", "placeholder", "content"]
});

export const i18n = Object.freeze({
  getLocale: () => locale,
  hasUserChanged: () => userChanged,
  setLocale
});
